"""
Phase 7: Live Capture Feature Parity Verification and Stress Testing.

Compares flow features generated by the live capture / PCAP parsing path (pcap_parser.py,
feature_mapper.py) against reference flow records from CIC-IDS-2017.

AUDIT SCOPE:
1. Schema & Feature Coverage:
   - Compares 80 expected training features against features generated by the parser.
   - Identifies exact matches, mapped overrides, dummy/constant features, and unmapped features.
2. Value Discrepancy & Scaling Analysis:
   - Evaluates unit scaling (microseconds vs seconds), TCP flag bitmask alignment,
     and rate calculations (Flow Bytes/s, Flow Packets/s).
3. Robustness & Malformed Packet Stress Testing:
   - Partial flows (single-packet, SYN-only, FIN-without-SYN).
   - Zero-duration packets (division-by-zero protection).
   - Truncated packet headers and non-IP frames (ARP, ICMP).
   - Corrupted or negative inter-arrival timestamps.
4. Operational Integrity Claim:
   - Documents matching rules, error distributions, and produces
     docs/FEATURE_PARITY_LIVE_CAPTURE.md.

Usage:
    python training/verify_feature_parity.py --data-dir data --output-dir docs
"""

