        f"- **Total Model Features Required**: {schema_info['total_required']}",
        f"- **Features Produced by the Scapy Upload Parser**: {schema_info['total_generated']}",
        f"- **Direct Feature Matches**: {len(schema_info['matched_features'])} ({len(schema_info['matched_features'])/schema_info['total_required']*100:.1f}%)",
        f"- **Missing / Uncomputed Features**: {len(schema_info['missing_features'])}",
        "",
